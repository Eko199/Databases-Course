CREATE VIEW BritishShips
AS
	SELECT NAME, s.CLASS, TYPE, NUMGUNS, BORE, DISPLACEMENT, LAUNCHED
	FROM SHIPS s
	JOIN CLASSES c ON s.CLASS = c.CLASS
	WHERE COUNTRY = 'Gt.Britain'
GO

SELECT NUMGUNS, DISPLACEMENT
FROM BritishShips
WHERE TYPE = 'bb' AND LAUNCHED < 1919

SELECT NUMGUNS, DISPLACEMENT
FROM SHIPS s
JOIN CLASSES c ON s.CLASS = c.CLASS
WHERE COUNTRY = 'Gt.Britain' AND TYPE = 'bb' AND LAUNCHED < 1919
GO

CREATE VIEW AvgDisplacement
AS
	SELECT COUNTRY, AVG(DISPLACEMENT) AS [Average Displacement]
	FROM CLASSES
	GROUP BY COUNTRY
GO

CREATE OR ALTER VIEW SunkenShips
AS
	SELECT SHIP, BATTLE
	FROM OUTCOMES
	WHERE RESULT = 'sunk'
GO

