CREATE VIEW actorMovieCount
AS
	SELECT NAME, COUNT(MOVIETITLE) AS MOVIESCOUNT
	FROM MOVIESTAR
	LEFT JOIN STARSIN ON NAME = STARNAME
	GROUP BY NAME
GO

