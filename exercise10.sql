CREATE VIEW DamagedBattles
AS
	SELECT BATTLE
	FROM OUTCOMES
	JOIN SHIPS ON SHIP = NAME
	WHERE CLASS NOT IN (SELECT CLASS FROM ManyGuns)
	GROUP BY BATTLE
	HAVING COUNT(SHIP) >= 3 AND COUNT(CASE WHEN RESULT = 'damaged' THEN 1 END) > 0
GO