CREATE VIEW prob3
AS
	SELECT 
		s.NAME, 
		c.CLASS, 
		BATTLE, 
		(SELECT COUNT(DISTINCT NAME) 
			FROM SHIPS s1
			JOIN CLASSES c1 ON s1.CLASS = c1.CLASS
			JOIN OUTCOMES ON NAME = SHIP
			WHERE NUMGUNS > 8 AND BATTLE = o.BATTLE
		) AS [Ships in Battle],
		LAUNCHED,
		YEAR(DATE) AS [Year of Battle]
	FROM SHIPS s
	JOIN CLASSES c ON s.CLASS = c.CLASS
	JOIN OUTCOMES o ON NAME = SHIP
	JOIN BATTLES b ON BATTLE = b.NAME
	WHERE NUMGUNS > 8
GO

