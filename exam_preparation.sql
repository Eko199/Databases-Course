--Problem 1
USE ships

SELECT 
	c.CLASS,
	SUM(CASE WHEN DISPLACEMENT > 30000 THEN 1 ELSE 0 END) AS [Big Ships],
	COUNT(o.SHIP) AS [Victory Ships],
	SUM(CASE WHEN LAUNCHED > 1942 THEN 1 ELSE 0 END) AS [New Ships]
FROM CLASSES c
JOIN SHIPS s ON c.CLASS = s.CLASS
LEFT JOIN (SELECT DISTINCT SHIP FROM OUTCOMES WHERE RESULT = 'ok') o
	ON NAME = o.SHIP
GROUP BY c.CLASS
HAVING COUNT(DISTINCT LAUNCHED) >= 3

